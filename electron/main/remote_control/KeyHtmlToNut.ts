const metaKey = () => {
  if (process.platform === 'darwin') return 'cmd'
  if (process.platform === 'linux') return 'meta'

  return 'win'
}

export const keyHtmlToNut = (code: ClientKeys) => {
  if (code === 'MetaLeft') return metaKey()

  return keyByCode[code]
}
